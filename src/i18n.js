export function getLocale() {
  return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
}

export function setLocale(locale) {
  const nextLocale = normalizeLocale(locale);
  window.localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
  document.documentElement.lang = nextLocale;
  return nextLocale;
}

export function t(key, params = {}, locale = getLocale()) {
  const dictionary = messages[normalizeLocale(locale)] || messages[DEFAULT_LOCALE];
  const fallbackDictionary = messages[DEFAULT_LOCALE];
  const template = dictionary[key] ?? fallbackDictionary[key] ?? key;

  return template.replace(/\{(\w+)\}/g, (_match, token) => (
    params[token] == null ? `{${token}}` : String(params[token])
  ));
}

export function translateDom(root = document) {
  const locale = getLocale();

  root.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (!key) {
      return;
    }

    element.textContent = t(key, {}, locale);
  });

  root.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    const attributeName = element.dataset.i18nAttr;
    const key = element.dataset.i18nAttrKey;
    if (!attributeName || !key) {
      return;
    }

    element.setAttribute(attributeName, t(key, {}, locale));
  });

  root.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (!key) {
      return;
    }

    element.setAttribute('placeholder', t(key, {}, locale));
  });

  root.querySelectorAll('[data-i18n-tooltip]').forEach((element) => {
    const key = element.dataset.i18nTooltip;
    if (!key) {
      return;
    }

    element.setAttribute('data-tooltip', t(key, {}, locale));
  });

  root.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (!key) {
      return;
    }

    element.setAttribute('aria-label', t(key, {}, locale));
  });

  document.documentElement.lang = locale;
}

